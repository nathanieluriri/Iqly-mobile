"""Builds the Android notification small icon from the official logomark.

Android draws a small icon from its alpha only. Since Android 12 the
notification header puts it inside a circle of the notification colour and
paints the icon in the card's own colour, so a solid tile with the bulb and
the corner sweep cut out reads like the logomark: the cut-outs show the
colour the way the mark shows its orange. The paths are the official ones,
combined with boolean operations, never redrawn.

Run from the repo root:  python3 tool/gen_status_icon.py   (needs skia-pathops, fonttools)
"""

import re
from pathlib import Path

import pathops
from fontTools.svgLib.path import parse_path

ROOT = Path(__file__).resolve().parent.parent
MARK = ROOT / "assets/brand/iqly-logomark.svg"
OUT = ROOT / "android/app/src/main/res/drawable/ic_stat_iqly.xml"
GLYPH_FILL = "#F58028"
VIEWPORT = 1000
# Material's 24dp status icon keeps a 1dp margin around its live area.
MARGIN = VIEWPORT / 24


def paths(svg: str) -> list[tuple[str, str]]:
    found = []
    for attrs in re.findall(r"<path\b([^>]*)/?>", svg):
        d = re.search(r'\bd="([^"]*)"', attrs).group(1)
        fill = re.search(r'\bfill="([^"]*)"', attrs)
        found.append((d, fill.group(1).upper() if fill else "#000000"))
    return found


def to_path(d: str) -> pathops.Path:
    path = pathops.Path()
    parse_path(d, path.getPen())
    return path


def number(value: float) -> str:
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return "0" if text == "-0" else text


def svg_d(path: pathops.Path) -> str:
    letters = {"moveTo": "M", "lineTo": "L", "qCurveTo": "Q", "curveTo": "C"}
    parts = []
    for verb, points in path.segments:
        if verb == "closePath":
            parts.append("Z")
            continue
        coords = " ".join(f"{number(x)} {number(y)}" for x, y in points)
        if verb == "qCurveTo" and len(points) > 2:
            raise ValueError("implied on-curve points are not expected here")
        parts.append(f"{letters[verb]}{coords}")
    return "".join(parts)


def main() -> None:
    svg = MARK.read_text()
    found = paths(svg)
    tile = to_path(found[0][0])
    glyph = pathops.Path()
    for d, fill in found:
        if fill == GLYPH_FILL:
            glyph = pathops.op(glyph, to_path(d), pathops.PathOp.UNION)
    knocked = pathops.op(tile, glyph, pathops.PathOp.DIFFERENCE)
    scale = (VIEWPORT - 2 * MARGIN) / VIEWPORT
    OUT.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tool/gen_status_icon.py. Do not edit by hand. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp"\n'
        '    android:height="24dp"\n'
        f'    android:viewportWidth="{VIEWPORT}"\n'
        f'    android:viewportHeight="{VIEWPORT}">\n'
        "    <group\n"
        f'        android:scaleX="{scale:.5f}"\n'
        f'        android:scaleY="{scale:.5f}"\n'
        f'        android:translateX="{MARGIN:.5f}"\n'
        f'        android:translateY="{MARGIN:.5f}">\n'
        "        <path\n"
        '            android:fillColor="#FFFFFFFF"\n'
        f'            android:pathData="{svg_d(knocked)}" />\n'
        "    </group>\n"
        "</vector>\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
